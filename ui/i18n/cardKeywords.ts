const BY_LOCALE: Record<string, Record<string, string>> = {
  "zh-Hans": Object.fromEntries(
    Object.entries(KEYWORDS).map(([key, name]) => [key, name.hans]),
  ),
  "zh-Hant": Object.fromEntries(
    Object.entries(KEYWORDS).map(([key, name]) => [key, name.hant]),
  ),
};

// Longest-first so "double strike" wins over "double", "trample over
// planeswalkers" over "trample", etc.
const SORTED_KEYS: Record<string, string[]> = {
  "zh-Hans": Object.keys(BY_LOCALE["zh-Hans"]!).sort((a, b) => b.length - a.length),
  "zh-Hant": Object.keys(BY_LOCALE["zh-Hant"]!).sort((a, b) => b.length - a.length),
};

/**
 * Translate an English keyword label (optionally with a cost/parameter suffix
 * such as "Ward:{2}" or "Dredge(2)") into the active Chinese locale. Anything
 * unmapped is returned unchanged, so untranslated keywords keep working.
 */
export function translateKeyword(keyword: string, locale: string = i18n.locale): string {
  const table = BY_LOCALE[locale];
  const keys = SORTED_KEYS[locale];
  if (!table || !keys) return keyword;
  const trimmed = keyword.trim();
  const lower = trimmed.toLowerCase();
  if (!lower) return keyword;
  for (const key of keys) {
    if (!lower.startsWith(key)) continue;
    const next = lower.charAt(key.length);
    if (next && /[a-z0-9]/.test(next)) continue;
    return table[key]! + trimmed.slice(key.length);
  }
  return keyword;
}
