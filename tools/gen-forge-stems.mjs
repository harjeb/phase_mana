/**
 * Generates `ui/lib/forgeCardStemOverrides.ts`: the exceptions where the
 * slug of a card *name* is not the Forge card-script filename stem.
 *
 * Local card-image packs mirror Forge's `cardsfolder` layout
 * (`<letter>/<forge-stem>.<variant>.webp`), and `forgeCardStem()` reproduces
 * Forge's own name -> filename rule (`CardScriptInfo.getScriptFor`), so the
 * common case needs no data at all. The exceptions are the multi-face cards
 * whose file is named after *both* faces (`kazuuls_fury` -> real file
 * `kazuuls_fury_kazuuls_cliffs`) while the engine only ever emits the front
 * face, plus a handful of name normalisations (accented, dotted, ampersand).
 *
 * Usage: node tools/gen-forge-stems.mjs /path/to/forge/forge-gui/res/cardsfolder
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node tools/gen-forge-stems.mjs <cardsfolder>");
  process.exit(1);
}

/** Mirrors forge-gui CardScriptInfo.getScriptFor, with NFD accent stripping
 *  first so `Lim-Dûl's Vault` keeps its `u` (`lim_duls_vault`). */
export function forgeCardStem(name) {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^-a-z0-9_\s]/g, "")
    .replace(/[-\s]/g, "_")
    .replace(/__/g, "_");
}

const scripts = [];
for (const shard of readdirSync(root, { withFileTypes: true })) {
  if (!shard.isDirectory()) continue;
  for (const file of readdirSync(join(root, shard.name))) {
    if (!file.endsWith(".txt")) continue;
    const names = [
      ...readFileSync(join(root, shard.name, file), "utf8").matchAll(/^Name:(.*)$/gm),
    ].map((m) => m[1].trim());
    if (names.length > 0) scripts.push({ stem: file.slice(0, -4), names });
  }
}
// A slug that is itself some other card's filename must never be rewritten.
const stems = new Set(scripts.map((s) => s.stem));
const overrides = {};
for (const { stem, names } of scripts) {
  for (const name of [names[0], names.join(" // ")]) {
    const slug = forgeCardStem(name);
    if (slug !== stem && !stems.has(slug)) overrides[slug] = stem;
  }
}

const out = "ui/lib/forgeCardStemOverrides.ts";
writeFileSync(
  out,
  `// Generated by tools/gen-forge-stems.mjs from Forge's cardsfolder. Do not edit.\n` +
    `// Slugs whose Forge card-script filename is not the slug of any name the\n` +
    `// engine can emit (multi-face cards, accented/dotted names).\n` +
    `export const FORGE_CARD_STEM_OVERRIDES: Record<string, string> = ${JSON.stringify(overrides, null, 0)};\n`,
);
console.error(`${scripts.length} scripts -> ${Object.keys(overrides).length} overrides in ${out}`);
